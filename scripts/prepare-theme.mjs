import { readFile, writeFile } from 'node:fs/promises';
import { installTheme } from '../packages/portable/browser/theme.js';
const config = JSON.parse(await readFile(new URL('../src/config/theme.json', import.meta.url), 'utf8'));
export const themeBootstrap = '// Generated by npm run prepare:theme. Runs before CSS/React.\n(' + installTheme.toString() + ')(' + JSON.stringify(config) + ');\n';
const target = new URL('../public/theme.js', import.meta.url);
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8') !== themeBootstrap) throw new Error('Stale theme bootstrap. Run npm run prepare:theme.');
} else await writeFile(target, themeBootstrap);
